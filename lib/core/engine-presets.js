export const ENGINE_PRESETS = [...VIDEO_PRESETS, ...IMAGE_PRESETS];

// 按 key 取一条预设（供「新建引擎」用）
export function getEnginePreset(key) {
  return ENGINE_PRESETS.find((p) => p.key === key) || null;
}

// 把预设展开成一条可入库的 engines[] 配置（只给默认值，key 留给用户填）
export function presetToEngine(preset, id) {
  if (!preset) return null;
  return {
    id: id || 'eng_' + preset.key.replace(/[^a-z0-9]/gi, '_') + '_' + Math.random().toString(36).slice(2, 7),
    name: preset.name,
    kind: preset.kind,
    enabled: false, // 默认不启用：配了一半的引擎不能拿去跑生产
    tasks: Array.isArray(preset.tasks) ? [...preset.tasks] : [],
    apiKey: '',
    presetKey: preset.key,
    ...preset.config,
  };
}

// 给前端用的精简列表（不带 config，避免把模板体当表单默认值之外的东西暴露）
export function listEnginePresets() {
  return ENGINE_PRESETS.map((p) => ({
    key: p.key,
    name: p.name,
    vendor: p.vendor,
    kind: p.kind,
    tasks: p.tasks,
    ready: p.ready,
    docs: p.docs,
    authNote: p.authNote,
    note: p.note || '',
    why: p.why || '',
  }));
}
