/** 邻镜级一条（QH-3） */
export const NEIGHBOR_RULE_IDS = Object.freeze(['A-06']);
/** 状态级（QH-4） */
export const STATE_RULE_IDS = Object.freeze(
  RULE_IDS.filter((id) => SCOPE_OF[id] === 'state'),
);
/** 审计类：不由输入行决定，依赖是"其它规则的产出" */
export const AUDIT_RULE_IDS = Object.freeze(['S-20', 'S-21', 'S-25']);

/**
 * 某字段被哪些规则读取（供失效计算按字段反查规则）。
 *
 * 前缀匹配：字段 `shot.shot_size` 命中声明 `shot.shot_size`；
 * 字段 `blockings` 命中所有 `blockings[*].*`（整表变化）。
 */
export function rulesReadingField(field) {
  const f = String(field ?? '').replace(/\[\*\]/g, '').replace(/\.\*$/, '');
  const out = [];
  for (const id of RULE_IDS) {
    const hit = RULE_DEPS[id].fields.some((decl) => {
      const d = decl.replace(/\[\*\]/g, '');
      return f === d || f.startsWith(`${d}.`) || d.startsWith(`${f}.`);
    });
    if (hit) out.push(id);
  }
  return out;
}
