/** 按作用域分组（QIS 的粒度由它决定，§7.8.1.3） */
export const SCOPE_OF = Object.freeze(
  Object.fromEntries(Object.entries(RULE_DEPS).map(([id, d]) => [id, d.scope])),
);

/** 章级三条（QH-2）：改一镜即令全章这三条的规则级 Hash 变 */
